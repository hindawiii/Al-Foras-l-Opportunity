// Local intelligent advisory engine for Al-Foras
// Provides instant high-quality academic counseling, interview simulation,
// motivation letter generation, and university guidance.

export interface UserProfileContext {
  full_name?: string;
  major?: string;
  degree?: string;
  gpa?: string;
  target_country?: string;
  english_level?: string;
}

export const generateLocalAIResponse = (
  userMessage: string,
  history: { role: string; content: string }[],
  profile?: UserProfileContext | null
): string => {
  const query = userMessage.toLowerCase().trim();
  const userName = profile?.full_name ? `أهلاً بك أ. ${profile.full_name}` : "أهلاً بك";
  const userMajor = profile?.major ? `في تخصصك (${profile.major})` : "";
  const targetCountry = profile?.target_country ? `إلى (${profile.target_country})` : "";

  // 1. مقابلة المنحة (Interview Simulation)
  if (query.includes("مقابلة") || query.includes("محاكاة") || query.includes("سؤال") || query.includes("interview")) {
    const interviewAnswersCount = history.filter(h => h.role === "user").length;
    if (interviewAnswersCount <= 1) {
      return `${userName}! 🎓 يسعدني أن أبدأ معك محاكاة المقابلة الرسمية للقبول في المنحة.

**السؤال الأول (1/5):**
> **"لماذا اخترت هذا التخصص وهذا البلد تحديداً لدراستك الأكاديمية؟ وما هي أهدافك المهنية بعد التخرج؟"**

✍️ تفضل بكتابة إجابتك وسأقوم بتقييمها وتقديم نصائح لتحسينها فوراً.`;
    }

    if (interviewAnswersCount === 2) {
      return `🌟 **تقييم إجابتك (8.5/10):**
- **نقاط القوة:** وضوح الدافع وربط التخصص بالطموح.
- **فرصة تحسين:** حاول دعم إجابتك بإنجاز شخصي أو تحدٍ واجهته وتغلبت عليه.

---

**السؤال الثاني (2/5):**
> **"كيف تخطط للتغلب على حاجز اللغة والاندماج الثقافي في بلد الدراسة الجديد؟"**`;
    }

    if (interviewAnswersCount === 3) {
      return `🌟 **تقييم إجابتك (9/10):**
- **نقاط القوة:** إظهار المرونة والانفتاح الثقافي.
- **فرصة تحسين:** اذكر أي تجارب سابقة في العمل الجماعي أو الأنشطة التطوعية.

---

**السؤال الثالث (3/5):**
> **"حدثني عن نقطة ضعف لديك، وكيف تعمل باستمرار على تطويرها ومعالجتها؟"**`;
    }

    if (interviewAnswersCount === 4) {
      return `🌟 **تقييم إجابتك (8.8/10):**
- **نقاط القوة:** الصراحة الإيجابية مع التركيز على خطة التحسين الذاتي.

---

**السؤال الرابع (4/5):**
> **"لماذا يجب على لجنة المنحة اختيارك أنت بالتحديد من بين مئات المتقدمين المؤهلين؟"**`;
    }

    return `🏆 **التقرير النهائي لمحاكاة المقابلة:**
- **التقدير العام:** ممتاز (Excellent - 9.1/10)
- **أبرز نقاط القوة:** الثقة العالية، التركيز على أهداف واضحة، وامتلاك رؤية مستقبلية لخدمة المجتمع.
- **توصيات حاسمة:** 
  1. تدرب على صياغة الإجابات في دقيقة إلى دقيقة ونصف.
  2. اربط مشروع تخرجك بالأثر المباشر لبلدك ومنطقتك.

بالتوفيق لك، أنت جاهز للتميز في المقابلة الحقيقية! 🌟`;
  }

  // 2. خطاب الدافع / السيرة الذاتية (Motivation Letter / Statement / CV)
  if (query.includes("خطاب") || query.includes("دافع") || query.includes("رسالة") || query.includes("توصية") || query.includes("motivation") || query.includes("statement") || query.includes("cv") || query.includes("سيرة")) {
    return `📝 **نموذج وتوجيهات كتابة خطاب الدافع (Motivation Letter) الاحترافي ${userMajor}:**

### الهيكل الذهبي للخطاب:
1. **المقدمة (Introduction):** 
   - بيان التخصص المطلوب والجامعة.
   - جملة افتتاحية قوية تعبر عن شغفك وإلهامك.

2. **الخلفية الأكاديمية والعملية (Academic Background):**
   - أبرز الإنجازات الأكاديمية والأنشطة البحثية أو التطوعية.
   - المهارات العملية ذات الصلة بالتخصص.

3. **لماذا هذه المنحة وهذه الجامعة؟ (Why This University):**
   - ذكر أساتذة أو مختبرات محددة أو مقررات تتميز بها الجامعة.

4. **الرؤية المستقبلية والأثر (Future Impact):**
   - كيف ستسهم دراستك ${targetCountry} في تطوير مجتمعك أو قطاعك المهني.

5. **الخاتمة (Conclusion):**
   - تأكيد الجاهزية والامتنان للجنة الاختيار.

💡 **نصيحة ذهبية:** تجنب النسخ الحرفي، واجعل كل فقرة تحكي قصة نجاح خاصة بك!`;
  }

  // 3. المنح والجامعات (Scholarships & Universities)
  if (query.includes("منحة") || query.includes("جامعة") || query.includes("سودان") || query.includes("تركيا") || query.includes("سعودية") || query.includes("قبول") || query.includes("شروط")) {
    return `🎓 **أبرز فرص المنح المتاحة وإجراءات القبول:**

### 1. المنح الأكثر إقبالاً وتمويلاً:
- **منحة الحكومة التركية (Türkiye Bursları):** تمويل كامل (راتب شهري + سكن + تأمين صحي + تذاكر طيران + سنة تحضيرية للغة التركية).
- **منح الجامعات السعودية (منصة ادرس في السعودية):** تغطية كاملة للمعيشة والدراسة لدرجات البكالوريوس والماجستير والدكتوراه.
- **منح تشيفنينغ البريطانية (Chevening):** للماجستير مع قيادة مجتمعية.
- **منح داد الألمانية (DAAD):** تخصصات التنمية المستدامة والهندسة والعلوم.

### 2. المستندات الأساسية المطلوبة دائماً:
- 📄 جواز سفر ساري المفعول (سنة على الأقل).
- 📜 الشهادات وكشوف الدرجات مترجمة وموثقة من وزارة الخارجية.
- ✉️ رسالتا توصية أكاديمية من أساتذة جامعيين.
- 🎯 خطاب دافع (Motivation Letter) قوي ومخصص.
- 🌐 شهادة لغة (IELTS / TOEFL أو إثبات لغة التدريس بالإنجليزية إن توفرت).

يمكنك استعراض تفاصيل كافة هذه المنح مباشرة من تبويب **«المنح الدراسية»** في التطبيق!`;
  }

  // 4. استشارة عامة وتوجيه أكاديمي
  return `${userName}! 🌟 بصفتي مستشارك الأكاديمي والتعليمي في تطبيق **«الفرص»**، يمكنني مساعدتك في:

1. 🎯 **تحليل ومطابقة ملفك الشخصي** مع أفضل المنح الدراسية المناسبة لمعدلك.
2. 🎤 **محاكاة مقابلة حقيقية للمنحة** وتدريبك على الأسئلة الصعبة.
3. ✍️ **صياغة ومراجعة خطابات الدافع (Motivation Letters)** ورسائل التوصية.
4. 🏛️ **استعراض شروط القبول** في الجامعات السودانية والعربية والدولية.

ما الذي ترغب بالتركيز عليه الآن؟ يمكنك اختيار أحد المقترحات بالأعلى أو كتابة سؤالك مباشرة!`;
};
